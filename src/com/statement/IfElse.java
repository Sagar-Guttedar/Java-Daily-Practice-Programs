public class IfElse{
    int age;

    public void store(int x){
        age = x;
    }

    public void check(){
        if(age >= 18){
            System.out.println("Your age is : "+age);
            System.out.println("You can go and vote");
        }else{
            System.out.println("Your age is :"+age);
            System.out.println("You cannot vote");
        }
    }

    public static void main(String[] args) {
        IfElse i = new IfElse();
        i.store(19);
        i.check();
    }
}